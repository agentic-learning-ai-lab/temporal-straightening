#!/usr/bin/env python3
"""Regenerate RESULTS.txt from the raw plan logs.

Reads each condition's plan_logs/{gd,mpc}_seed{100,200,300}_chunk{00..40}.log,
parses the `Success rate:` lines emitted by plan.py's evaluator, pools the 5
chunks per seed into a 50-sample rate, and reports mean +/- population-std over
the 3 seeds. Run from anywhere:  python pusht_reproduction/make_results.py

The 'ours' numbers are computed here from the logs — nothing is hand-entered.
The 'paper' column is transcribed from Table 1 (arXiv:2603.12231v2), PushT / GD.
"""
import os, re, glob, statistics as st

HERE = os.path.dirname(os.path.abspath(__file__))
SEEDS = ("100", "200", "300")
OFFSETS = ("00", "10", "20", "30", "40")

# (folder, description, paper open-loop, paper MPC)
CONDS = [
    ("cls",           "DINOv2 CLS (1x384)",                                        "19.33 +/- 8.22", "28.00 +/- 1.63"),
    ("patch",         "DINOv2 patch (14x14x384, no projector)",                    "56.00 +/- 4.32", "66.00 +/- 4.90"),
    ("patchproj",     "DINOv2 patch+proj (14x14x8), straighten OFF",               "70.00 +/- 1.63", "78.67 +/- 0.94"),
    ("straightening", "DINOv2 patch+proj (14x14x8), straighten ON (agg, l=0.1)",   "77.33 +/- 6.18", "85.33 +/- 4.99"),
]


def seed_rate(folder, tag, seed):
    """Pooled 50-sample success rate (%) for one condition/planner/seed."""
    chunk_rates = []
    for o in OFFSETS:
        log = os.path.join(HERE, folder, "plan_logs", f"{tag}_seed{seed}_chunk{o}.log")
        vals = re.findall(r"Success rate:\s*([0-9.]+)", open(log, errors="ignore").read())
        if not vals:
            raise ValueError(f"no 'Success rate' in {log}")
        chunk_rates.append(float(vals[-1]) * 100.0)
    return sum(chunk_rates) / len(chunk_rates)  # equal chunks -> pooled 50-sample rate


def summarize(folder, tag):
    per_seed = [seed_rate(folder, tag, s) for s in SEEDS]
    mean = sum(per_seed) / len(per_seed)
    sd = st.pstdev(per_seed) if len(per_seed) > 1 else 0.0
    return per_seed, mean, sd


def main():
    lines = []
    W = lines.append
    W("PushT Reproduction - Table 1 (DINOv2 rows), GD planner")
    W("Paper: Temporal Straightening for Latent Planning (arXiv:2603.12231v2), PushT column.")
    W("Generated by make_results.py from the raw plan_logs (Success rate lines from plan.py).")
    W("50 test samples x 3 seeds (100/200/300), pooled from 5x10 chunks. Values = mean +/- pop-std %.")
    W("")
    header = f"{'condition':<15} {'open-loop (ours)':>18} {'paper':>16} {'MPC (ours)':>18} {'paper':>16}"
    W(header)
    W("-" * len(header))
    detail = []
    for folder, desc, p_ol, p_mpc in CONDS:
        ol_seeds, ol_m, ol_sd = summarize(folder, "gd")
        mpc_seeds, mpc_m, mpc_sd = summarize(folder, "mpc")
        W(f"{folder:<15} {f'{ol_m:.2f} +/- {ol_sd:.2f}':>18} {p_ol:>16} "
          f"{f'{mpc_m:.2f} +/- {mpc_sd:.2f}':>18} {p_mpc:>16}")
        detail.append((folder, desc, ol_seeds, ol_m, ol_sd, mpc_seeds, mpc_m, mpc_sd, p_ol, p_mpc))
    W("")
    W("Per-seed breakdown (pooled 50-sample rate per seed):")
    for folder, desc, ol_seeds, ol_m, ol_sd, mpc_seeds, mpc_m, mpc_sd, p_ol, p_mpc in detail:
        W("")
        W(f"[{folder}] {desc}")
        W(f"  open-loop GD: " + "  ".join(f"seed{s}={r:.1f}" for s, r in zip(SEEDS, ol_seeds))
          + f"   -> {ol_m:.2f} +/- {ol_sd:.2f}   (paper {p_ol})")
        W(f"  GD-MPC:       " + "  ".join(f"seed{s}={r:.1f}" for s, r in zip(SEEDS, mpc_seeds))
          + f"   -> {mpc_m:.2f} +/- {mpc_sd:.2f}   (paper {p_mpc})")

    out = os.path.join(HERE, "RESULTS.txt")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
