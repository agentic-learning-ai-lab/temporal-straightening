#!/usr/bin/env python3
"""Regenerate RESULTS.txt and per-condition summaries from plan_logs.

Reads each condition's plan_logs/gd_seed{100,200,300}_chunk{00..40}.log,
parses the `Success rate:` lines from plan.py, pools 5 chunks into a 50-sample
rate per seed, and reports mean +/- population std over 3 seeds.

Run from anywhere:  python pusht_ablations/make_results.py

R0 logs are imported from pusht_reproduction/straightening (aggcos1e-1 baseline).
R1–R3 populate when run_pusht_ablation_a100.sh plan completes.
"""
import os
import re
import statistics as st

HERE = os.path.dirname(os.path.abspath(__file__))
SEEDS = ("100", "200", "300")
OFFSETS = ("00", "10", "20", "30", "40")

# (folder, short label, training token, objective description)
CONDS = [
    (
        "r0_direction_only",
        "R0 direction-only",
        "aggcos1e-1",
        "0.1 × (1 − cos θ)",
    ),
    (
        "r1_speed_only",
        "R1 speed-only",
        "aggr1_1e-1",
        "0.1 × R1",
    ),
    (
        "r2_full_matched",
        "R2 full matched",
        "aggr2_5e-2",
        "0.05 × R2",
    ),
    (
        "r3_beta1",
        "R3 blended",
        "aggr3b1_1e-1",
        "0.1 × (R0 + R1)",
    ),
]


def seed_rate(folder, seed):
    chunk_rates = []
    for o in OFFSETS:
        log = os.path.join(HERE, folder, "plan_logs", f"gd_seed{seed}_chunk{o}.log")
        if not os.path.isfile(log):
            return None
        vals = re.findall(r"Success rate:\s*([0-9.]+)", open(log, errors="ignore").read())
        if not vals:
            return None
        chunk_rates.append(float(vals[-1]) * 100.0)
    if len(chunk_rates) != len(OFFSETS):
        return None
    return sum(chunk_rates) / len(chunk_rates)


def summarize(folder):
    per_seed = {}
    for s in SEEDS:
        rate = seed_rate(folder, s)
        if rate is not None:
            per_seed[s] = rate
    if len(per_seed) != len(SEEDS):
        return None
    vals = [per_seed[s] for s in SEEDS]
    mean = sum(vals) / len(vals)
    sd = st.pstdev(vals) if len(vals) > 1 else 0.0
    return per_seed, mean, sd


def write_condition_summary(folder, label, token, objective, per_seed, mean, sd, baseline_mean=None):
    path = os.path.join(HERE, folder, f"{folder}_results_3seed.txt")
    lines = [
        f"===== PushT trajectory-penalty ablation — {label} =====",
        f"config: encoder=dino_channel, projector dim 8, training.straighten={token}",
        f"objective: {objective}",
        "planner: open-loop GD (objective.alpha=1), 50 evals/seed as 5x10 chunks",
        "source: plan.py logs; generated by pusht_ablations/make_results.py",
        "",
        "per-seed success rate (%):",
    ]
    for s in SEEDS:
        lines.append(f"  seed {s:>4}: {per_seed[s]:6.2f}%")
    lines.append("")
    lines.append("n     = 3 seeds")
    lines.append(f"mean  = {mean:.2f} %")
    lines.append(f"std   = {sd:.2f} %   (population)")
    if baseline_mean is not None:
        lines.append(f"delta = {mean - baseline_mean:+.2f} pp vs R0")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(path, HERE)}")


def main():
    lines = []
    W = lines.append
    W("PushT Trajectory-Penalty Ablation — open-loop GD")
    W("Paper: Temporal Straightening for Latent Planning (arXiv:2603.12231v2)")
    W("Generated by pusht_ablations/make_results.py from plan_logs/ (Success rate lines from plan.py).")
    W("50 test samples x 3 seeds (100/200/300), pooled from 5x10 chunks. Values = mean +/- pop-std %.")
    W("Encoder: DINOv2 patch + channel projector (14x14x8). Training: 2 epochs (paper A.3).")
    W("")
    header = f"{'condition':<20} {'objective':<18} {'open-loop GD':>18}  {'Δ vs R0':>10}"
    W(header)
    W("-" * len(header))

    detail = []
    baseline_mean = None
    for folder, label, token, objective in CONDS:
        result = summarize(folder)
        if result is None:
            W(f"{folder:<20} {objective:<18} {'(pending)':>18}  {'':>10}")
            detail.append((folder, label, token, objective, None))
            continue
        per_seed, mean, sd = result
        if folder == "r0_direction_only":
            baseline_mean = mean
        delta = "" if baseline_mean is None or folder == "r0_direction_only" else f"{mean - baseline_mean:+.2f} pp"
        W(f"{folder:<20} {objective:<18} {f'{mean:.2f} +/- {sd:.2f}':>18}  {delta:>10}")
        write_condition_summary(folder, label, token, objective, per_seed, mean, sd,
                                None if folder == "r0_direction_only" else baseline_mean)
        detail.append((folder, label, token, objective, (per_seed, mean, sd)))

    W("")
    W("Per-seed breakdown (pooled 50-sample rate per seed):")
    for folder, label, token, objective, result in detail:
        W("")
        W(f"[{folder}] {label}  (training.straighten={token})")
        if result is None:
            W(f"  (pending — run: bash run_pusht_ablation_a100.sh plan {folder})")
            continue
        per_seed, mean, sd = result
        W("  open-loop GD: " + "  ".join(f"seed{s}={per_seed[s]:.1f}" for s in SEEDS)
          + f"   -> {mean:.2f} +/- {sd:.2f}")

    if baseline_mean is not None:
        W("")
        W(f"R0 baseline mean = {baseline_mean:.2f}% (imported from pusht_reproduction/straightening)")

    out = os.path.join(HERE, "RESULTS.txt")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
